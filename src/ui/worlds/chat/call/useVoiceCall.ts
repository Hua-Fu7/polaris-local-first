/**
 * Hands-free voice call loop:
 *
 *   ring -> (the assistant decides whether to pick up) -> listen -> (silence) ->
 *   transcribe -> send -> wait for reply -> speak -> listen
 *
 * The AI side has no ears, so every spoken turn is uploaded and turned into text
 * before it reaches the chat model; the reply comes back as audio generated by
 * the existing playback pipeline.
 */

export type VoiceCallPhase =
  | 'idle'
  /** 拨出后、接通前：电话在响，对方正在决定接不接。 */
  | 'ringing'
  | 'starting'
  | 'listening'
  | 'transcribing'
  | 'thinking'
  | 'speaking'
  /** 对方没接，屏幕上留一句它的解释，然后自动挂断。 */
  | 'declined'
  /** 判断没做成（模型或网络不给答案），按接不上处理。 */
  | 'unreachable'
  | 'error';

type VoiceCallTranslator = ReturnType<typeof useI18n>['t'];

/** 振铃至少响这么久：接通太快就不像在打电话了。 */
const MIN_RING_MS = 1000;

/** 判断请求最多等这么久，超时按接不上处理。 */
const RING_TIMEOUT_MS = 20000;

/**
 * 「XX 拒绝了你的通话」和「无法接通」在屏幕上停多久再自动收起。
 * 报错那条带着一整句重拨建议，留的时间和拒接一样长，否则看不清就没了。
 */
const DECLINED_HOLD_MS = 3200;
const UNREACHABLE_HOLD_MS = 3200;

export type VoiceCallController = {
  active: boolean;
  phase: VoiceCallPhase;
  /** 0..1 input level, for the listening meter. */
  level: number;
  /** Most recent utterance as transcribed. */
  heardText: string;
  /** Most recent reply as actually spoken. */
  replyText: string;
  /** 对方拒绝时留下的那句话，只在 declined 阶段有值；拒接本身由阶段文案说明。 */
  declineLine: string | null;
  /** 正在被呼叫的人，用来写「正在呼叫 XX」。 */
  collaboratorName: string;
  error: string | null;
  /** Whether both directions are configured enough to hold a call. */
  playbackReady: boolean;
  transcriptionReady: boolean;
  /** True while the microphone is muted: the assistant cannot hear you. */
  muted: boolean;
  /** True when the reply plays through the loudspeaker instead of the earpiece. */
  speakerphone: boolean;
  /** False where the platform routes output itself, so the switch is hidden. */
  speakerphoneSupported: boolean;
  /** 用户主动拨给协作者：先振铃，由协作者决定接不接。 */
  start: () => void;
  /** 接听协作者打过来的那通电话：不振铃，直接接通。 */
  answerIncoming: () => void;
  end: () => void;
  /** Cuts the reply short and goes straight back to listening. */
  interrupt: () => void;
  toggleMute: () => void;
  toggleSpeakerphone: () => void;
  /**
   * 不想出声时可以改用键盘：面板打开期间麦克风是关的，打出去的字走的是和
   * 「说出来」完全相同的那条路 —— 一样进聊天记录，一样等回复、一样念出来。
   */
  keyboardOpen: boolean;
  /** 键盘输入框里正在打的那句话。 */
  draft: string;
  openKeyboard: () => void;
  closeKeyboard: () => void;
  setDraft: (value: string) => void;
  /** 把 draft 发出去。空内容会被忽略。 */
  sendDraft: () => void;
};

/** 振铃阶段的结果：接听（带判断理由）、没接（可能带一句解释），或压根没判断成。 */
type IncomingCallOutcome =
  | { status: 'accepted'; reason: string }
  | { status: 'declined'; line: string }
  | { status: 'unreachable' };

const POLL_INTERVAL_MS = 220;
const REPLY_TIMEOUT_MS = 180000;
const ERROR_RETRY_DELAY_MS = 2200;
/** Wait this long before retrying when the previous turn has not finished yet. */
const BUSY_RETRY_DELAY_MS = 250;
/** How often the loop checks whether the microphone has been unmuted again. */
const MUTE_POLL_MS = 120;
/** Spoken replies are capped so a long answer does not monologue forever. */
const MAX_SPEECH_CHARS = 700;

function sleep(ms: number) {
  return new Promise<void>((resolve) => {
    window.setTimeout(resolve, ms);
  });
}

/** Raw analyser RMS is tiny, so scale it into something a meter can show. */
function toMeterLevel(value: number) {
  return Math.min(1, value * 8);
}

function clampSpeechText(value: string) {
  const text = value.trim();
  if (text.length <= MAX_SPEECH_CHARS) return text;
  const head = text.slice(0, MAX_SPEECH_CHARS);
  const boundary = Math.max(
    head.lastIndexOf('。'),
    head.lastIndexOf('！'),
    head.lastIndexOf('？'),
    head.lastIndexOf('\n'),
    head.lastIndexOf('. '),
    head.lastIndexOf('! '),
    head.lastIndexOf('? ')
  );
  const cut = boundary > MAX_SPEECH_CHARS * 0.5 ? head.slice(0, boundary + 1) : head;
  return cut.trim();
}

function describeStartFailure(error: unknown, t: VoiceCallTranslator): string {
  if (error instanceof VoiceCallRecorderError) {
    if (error.kind === 'permission-denied') return t('chat.voiceCall.errorMicDenied');
    if (error.kind === 'unsupported') return t('chat.voiceCall.errorMicUnsupported');
    if (error.kind === 'no-microphone') return t('chat.voiceCall.errorNoMicrophone');
  }
  return error instanceof Error ? error.message : t('chat.voiceCall.errorStartFailed');
}

export function useVoiceCall(): VoiceCallController {
  const { t } = useI18n();
  const actions = useChatActions();
  const ui = useChatUi();
  const { conversation, messages, persona } = useChatStablePayload();
  const voiceGeneration = useRuntimeStore((state) => state.voiceGeneration);
  const voiceTranscription = useRuntimeStore((state) => state.voiceTranscription);
  // 来电判断走协作者自己的模型绑定，和主动消息决策层用的是同一套解析。
  const runtimeApi = useRuntimeStore(selectRuntimeApi);
  const runtimeProviders = useRuntimeStore(selectVisibleProviders);

  const [active, setActive] = useState(false);
  const [phase, setPhase] = useState<VoiceCallPhase>('idle');
  const [level, setLevel] = useState(0);
  const [heardText, setHeardText] = useState('');
  const [replyText, setReplyText] = useState('');
  const [declineLine, setDeclineLine] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [muted, setMuted] = useState(false);
  // A call opens on the earpiece, like a real one; the speaker is opt-in.
  const [speakerphone, setSpeakerphone] = useState(false);
  const [keyboardOpen, setKeyboardOpen] = useState(false);
  const [draft, setDraftState] = useState('');

  const recorderRef = useRef<VoiceCallRecorderLike | null>(null);
  const audioRef = useRef<HTMLAudioElement | null>(null);
  const audioUrlRef = useRef<string | null>(null);
  const resolvePlaybackRef = useRef<(() => void) | null>(null);
  const abortRef = useRef<AbortController | null>(null);
  /** Bumped on every start/end; in-flight async work bails when it goes stale. */
  const sessionRef = useRef(0);
  const activeRef = useRef(false);
  /** Read by the loop, which outlives any single render. */
  const mutedRef = useRef(false);
  const speakerphoneRef = useRef(false);
  /**
   * 键盘面板开着的时候麦克风关着，录音循环靠它决定要不要开新的一轮录音。
   * 循环跑在闭包外面，所以读 ref 而不是 state。
   */
  const keyboardOpenRef = useRef(false);
  /** 输入框里那句话的最新值，供 sendDraft 读取。 */
  const draftRef = useRef('');
  /**
   * 打出去的那句话，等着录音循环取走。
   *
   * 打字的发言和说出来的发言在「文本已就绪」之后完全同路，所以不另开一条
   * 发送链路，只把文本放在这里，由循环自己消费 —— 这样也不会绕过
   * `speakReply` / `waitForReply` 里那套会话失效检查。
   */
  const pendingTextRef = useRef<string | null>(null);
  /** 振铃结束之后自动收起通话界面的定时器。 */
  const dismissTimerRef = useRef<number | null>(null);
  /** 用户还没接就挂断时，用它掐掉还在飞的判断请求。 */
  const screeningAbortRef = useRef<AbortController | null>(null);
  /**
   * 这通电话最后是什么结局，挂断时照它往聊天记录里补一条。
   * 振铃还没结束就被挂断、或者压根没接通时留 null —— 没什么可记的。
   */
  const callOutcomeRef = useRef<
    | { kind: 'declined'; declineLine: string | null }
    | { kind: 'connected'; startedAt: number }
    | null
  >(null);
  const endRef = useRef<() => void>(() => undefined);
  /** 挂断后唤醒 AI 的入口，经 ref 稳定，避免 end() 因 actions 变化而频繁重建。 */
  const notifyCallEndedRef = useRef(actions.notifyCallEnded);
  useEffect(() => {
    notifyCallEndedRef.current = actions.notifyCallEnded;
  }, [actions.notifyCallEnded]);

  // The loop is an async function, so it reads live values through refs rather
  // than closing over render-time state.
  const uiRef = useRef(ui);
  const messagesRef = useRef<ChatMessage[]>(messages);
  const conversationRef = useRef(conversation);
  const personaRef = useRef(persona);
  const apiRef = useRef(runtimeApi);
  const providersRef = useRef(runtimeProviders);
  const generationRef = useRef(voiceGeneration);
  const transcriptionRef = useRef(voiceTranscription);
  const tRef = useRef(t);
  useEffect(() => {
    tRef.current = t;
  }, [t]);
  useEffect(() => {
    uiRef.current = ui;
  }, [ui]);
  useEffect(() => {
    messagesRef.current = messages;
  }, [messages]);
  useEffect(() => {
    conversationRef.current = conversation;
  }, [conversation]);
  useEffect(() => {
    personaRef.current = persona;
  }, [persona]);
  useEffect(() => {
    apiRef.current = runtimeApi;
  }, [runtimeApi]);
  useEffect(() => {
    providersRef.current = runtimeProviders;
  }, [runtimeProviders]);
  useEffect(() => {
    generationRef.current = voiceGeneration;
  }, [voiceGeneration]);
  useEffect(() => {
    transcriptionRef.current = voiceTranscription;
  }, [voiceTranscription]);

  const stopPlayback = useCallback(() => {
    const finish = resolvePlaybackRef.current;
    resolvePlaybackRef.current = null;
    const audio = audioRef.current;
    audioRef.current = null;
    if (audio) {
      audio.onended = null;
      audio.onerror = null;
      try {
        audio.pause();
      } catch {
        // Ignore: pausing an already-stopped element is fine.
      }
    }
    const url = audioUrlRef.current;
    audioUrlRef.current = null;
    if (url) URL.revokeObjectURL(url);
    // The native player settles its own promise from the Java side, so this both
    // silences it and unblocks the turn waiting on it.
    void stopNativeVoiceCallSpeech().catch(() => undefined);
    finish?.();
  }, []);

  const speakReply = useCallback(async (session: number, text: string) => {
    const speechText = clampSpeechText(text);
    if (!speechText) return;
    const settings = { ...generationRef.current, enabled: true };
    if (!settings.baseUrl?.trim() || !settings.apiKey?.trim()) {
      throw new Error(tRef.current('chat.voiceCall.errorPlaybackMissing'));
    }

    const controller = new AbortController();
    abortRef.current = controller;
    const result = await requestGeneratedSpeech({ settings, text: speechText, signal: controller.signal });
    if (sessionRef.current !== session || controller.signal.aborted) return;

    /*
     * Android plays through the native call route. A WebView `<audio>` lands on
     * the media route, which the speaker/earpiece switch cannot reach, so the
     * speaker key would do nothing to the reply.
     */
    if (canPlayNativeVoiceCallSpeech()) {
      const bytes = new Uint8Array(await result.blob.arrayBuffer());
      if (sessionRef.current !== session || controller.signal.aborted) return;
      await playNativeVoiceCallSpeech(bytesToBase64(bytes), result.blob.type || 'audio/mpeg');
      return;
    }

    const url = URL.createObjectURL(result.blob);
    audioUrlRef.current = url;
    const audio = new Audio(url);
    audioRef.current = audio;
    await new Promise<void>((resolve) => {
      resolvePlaybackRef.current = resolve;
      audio.onended = () => resolve();
      audio.onerror = () => resolve();
      void audio.play().catch(() => resolve());
    });
    resolvePlaybackRef.current = null;
    if (audioRef.current === audio) audioRef.current = null;
    if (audioUrlRef.current === url) {
      URL.revokeObjectURL(url);
      audioUrlRef.current = null;
    }
  }, []);

  /** Waits until a reply whose id was not in `baseline` has content. */
  const waitForReply = useCallback(async (session: number, baseline: Set<string>) => {
    const startedAt = Date.now();
    while (sessionRef.current === session && Date.now() - startedAt < REPLY_TIMEOUT_MS) {
      await sleep(POLL_INTERVAL_MS);
      if (sessionRef.current !== session) return null;
      const current = uiRef.current;
      if (current.sending || current.streaming) continue;
      const fresh = [...messagesRef.current]
        .reverse()
        .find((message) => message.role === 'assistant' && !baseline.has(message.id) && message.content.trim());
      if (fresh) return fresh;
    }
    return null;
  }, []);

  /**
   * Idles while muted. Muting stops capture outright rather than recording and
   * dropping: the system microphone indicator has to go away, and silence is the
   * honest thing to send to a speech-to-text endpoint.
   */
  const waitWhileMuted = useCallback(async (session: number) => {
    // 打字能穿过静音：麦克风关着只说明「听不见你」，不代表不能打一句话过去。
    while (
      sessionRef.current === session
      && mutedRef.current
      && !keyboardOpenRef.current
      && pendingTextRef.current === null
    ) {
      await sleep(MUTE_POLL_MS);
    }
  }, []);

  /**
   * 键盘面板开着时麦克风是关的，循环就停在这里。
   *
   * 不这么做的话，敲键盘的动静会被录成一整轮发言，转写出来一串没头没脑的字
   * 自己发出去。面板一关（或按下发送）这个循环立刻返回。
   */
  const waitWhileComposing = useCallback(async (session: number) => {
    while (sessionRef.current === session && keyboardOpenRef.current) {
      await sleep(MUTE_POLL_MS);
    }
  }, []);

  /** 取走等待发送的那句打字，取过一次就没了。 */
  const takePendingText = useCallback(() => {
    const text = pendingTextRef.current;
    pendingTextRef.current = null;
    return text;
  }, []);

  /**
   * 一句话（听来的或打出来的）走完剩下的行程：发出去、等回复、念出来。
   *
   * 两种输入在这里合流，所以「打字让小机说话」和「说话让小机说话」在聊天记录
   * 和语音上不会有任何差别。
   */
  const runTextTurn = useCallback(async (session: number, text: string) => {
    setHeardText(text);
    const baseline = new Set(messagesRef.current.map((message) => message.id));
    actions.setInputDraft(text);
    await actions.submit();
    if (sessionRef.current !== session) return;

    setPhase('thinking');
    const reply = await waitForReply(session, baseline);
    if (sessionRef.current !== session) return;
    if (!reply) throw new Error(tRef.current('chat.voiceCall.errorNoReply'));

    const spoken = buildAssistantSpeechText(reply.content);
    setReplyText(spoken);
    if (spoken) {
      setPhase('speaking');
      await speakReply(session, spoken);
    }
  }, [actions, speakReply, waitForReply]);

  const runLoop = useCallback(async (session: number) => {
    const recorder = recorderRef.current;
    if (!recorder) return;

    while (sessionRef.current === session) {
      try {
        /*
         * 打字的发言排在录音前面。
         *
         * 打字时麦克风是关着的，所以「有没有人要打字说话」这件事必须先问，
         * 不然循环会去开一轮注定要作废的录音。
         */
        const typed = takePendingText();
        if (typed) {
          await runTextTurn(session, typed);
          if (sessionRef.current !== session) return;
          continue;
        }

        setPhase('listening');
        setLevel(0);
        if (keyboardOpenRef.current) {
          await waitWhileComposing(session);
          if (sessionRef.current !== session) return;
          continue;
        }
        if (mutedRef.current) {
          await waitWhileMuted(session);
          if (sessionRef.current !== session) return;
          continue;
        }
        const recording = await recorder.recordTurn({
          onLevel: (value) => setLevel(toMeterLevel(value))
        });
        if (sessionRef.current !== session) return;
        setLevel(0);
        /*
         * 这一轮录音是被「打开键盘」或「按下发送」打断的（两者都会 cancel 当前
         * 录音让这里返回），音频作废：去循环顶部处理那次打字，别把敲键盘的
         * 声音当成一句话发出去。
         */
        if (keyboardOpenRef.current || pendingTextRef.current !== null) continue;

        setPhase('transcribing');
        const target = resolveTranscriptionTarget(transcriptionRef.current, generationRef.current);
        const text = (await transcribeAudio({
          target,
          audio: recording.blob,
          filename: `turn.${extensionForMimeType(recording.mimeType)}`
        })).trim();
        if (sessionRef.current !== session) return;
        if (!text) continue;

        await runTextTurn(session, text);
        if (sessionRef.current !== session) return;
      } catch (caught) {
        if (sessionRef.current !== session) return;
        /*
         * 被键盘打断的一轮不是失败。
         *
         * cancel() 让 recordTurn 抛什么由平台决定（原生侧并不是 no-speech），
         * 所以先认「是谁打断的」这个事实，再去看异常类型 —— 否则一打开键盘，
         * 屏幕上就会闪一条通话出错。
         */
        if (keyboardOpenRef.current || pendingTextRef.current !== null) continue;
        // A silent window is not an error: just keep listening. Neither is a
        // turn dropped by the mute button — the loop idles on the next pass.
        if (
          caught instanceof VoiceCallRecorderError
          && (caught.kind === 'no-speech' || caught.kind === 'muted')
        ) {
          continue;
        }
        setError(caught instanceof Error ? caught.message : tRef.current('chat.voiceCall.errorGeneric'));
        setPhase('error');
        setLevel(0);
        await sleep(ERROR_RETRY_DELAY_MS);
        if (sessionRef.current !== session) return;
        setError(null);
      }
    }
  }, [runTextTurn, takePendingText, waitForReply, waitWhileComposing, waitWhileMuted]);

  // start() is defined before runLoop in render order, so it reaches the loop
  // through a ref instead of capturing a stale identity.
  const runLoopRef = useRef(runLoop);
  useEffect(() => {
    runLoopRef.current = runLoop;
  }, [runLoop]);

  const clearDismissTimer = useCallback(() => {
    if (dismissTimerRef.current === null) return;
    window.clearTimeout(dismissTimerRef.current);
    dismissTimerRef.current = null;
  }, []);

  /** 未接听 / 接不上时，让那行字在屏幕上停一会儿再收起整块界面。 */
  const holdThenEnd = useCallback((session: number, holdMs: number) => {
    clearDismissTimer();
    dismissTimerRef.current = window.setTimeout(() => {
      dismissTimerRef.current = null;
      if (sessionRef.current !== session) return;
      endRef.current();
    }, holdMs);
  }, [clearDismissTimer]);

  /**
   * 振铃，然后由协作者本人决定接不接。
   *
   * 这一层之所以存在：用户按下打电话之后，接听与否应该是角色的事，而不是默认就通。
   * 判断用的是一次独立补全（`runIncomingCallDecision`），所以它不会在聊天里留下痕迹，
   * 也不会顺带触发生成一整轮回复。
   */
  const screenIncomingCall = useCallback(async (session: number): Promise<IncomingCallOutcome> => {
    // 没有人格就没有能替自己做决定的人，照旧直接接通，不把老行为弄坏。
    // 没有判断，自然也没有理由；留空，让接通记录走「方向中立」的文案。
    if (!personaRef.current) return { status: 'accepted', reason: '' };

    const controller = new AbortController();
    screeningAbortRef.current = controller;
    const startedAt = Date.now();
    const timer = window.setTimeout(() => controller.abort(), RING_TIMEOUT_MS);

    try {
      const decision = await runIncomingCallDecision({
        persona: personaRef.current,
        globalApi: apiRef.current,
        providers: providersRef.current,
        messages: messagesRef.current,
        signal: controller.signal
      });

      // 响铃有个下限，不然判断太快会让「振铃」一闪而过，整件事看起来像没发生。
      const remaining = MIN_RING_MS - (Date.now() - startedAt);
      if (remaining > 0) await sleep(remaining);

      if (sessionRef.current !== session) return { status: 'unreachable' };
      if (!decision) return { status: 'unreachable' };
      if (!decision.accept) return { status: 'declined', line: decision.line };
      return { status: 'accepted', reason: decision.reason };
    } catch {
      return { status: 'unreachable' };
    } finally {
      window.clearTimeout(timer);
      if (screeningAbortRef.current === controller) screeningAbortRef.current = null;
    }
  }, []);

  /**
   * 接听之后那一半：开麦、设路由、进听说循环。
   *
   * 听说循环从「听」开始，而不是先让 AI 开口。这是照着真实电话来的：你接起来先说
   * 一声「喂」，对面才说话。对方主动打过来的那通也一样，所以两个方向共用这段。
   */
  const enterConnectedCall = useCallback(async (session: number, acceptedReason?: string) => {
    try {
      setPhase('starting');
      // Only the WebView fallback cares about container formats: the native
      // recorder always emits 16kHz mono WAV, which every vendor accepts.
      const preferMp4 = resolveTranscriptionProviderType(transcriptionRef.current) === 'minimax';
      const recorder = createVoiceCallRecorder({ preferMp4 });
      recorderRef.current = recorder;

      await recorder.prime();
      if (sessionRef.current !== session) return;
      try {
        await recorder.setSpeakerphone(speakerphoneRef.current);
      } catch {
        // Routing is best effort; a call that cannot switch output still works.
      }
      if (sessionRef.current !== session) return;

      // 到这里麦克风真的开起来了，才算接通：往桥里登记这通活动通话，
      // 让引擎层的 hangUp 工具能挂断它；同时往聊天记录里留一条「已接通」，
      // 让模型在通话中的每一轮都能看到「我正在和用户通话」。
      const conversationId = conversationRef.current?.id ?? '';
      const collaboratorId = personaRef.current?.id ?? '';
      const collaboratorName = personaRef.current?.name?.trim() ?? '';
      registerActiveVoiceCall({
        conversationId,
        collaboratorId,
        collaboratorName,
        hangUp: () => endRef.current()
      });
      if (conversationId) {
        try {
          const chat = useChatStore.getState();
          const writable = chat.getConversationWritable(conversationId);
          if (writable) {
            chat.addMessage(writable, createVoiceCallConnectedNoteMessage({
              collaboratorName,
              acceptedReason,
              t: tRef.current
            }));
          }
        } catch {
          // 记不上就算了：通话本身已经接通，不值得为一条记录把通话流程炸掉。
        }
      }

      await runLoopRef.current(session);
    } catch (caught) {
      if (sessionRef.current !== session) return;
      setError(describeStartFailure(caught, tRef.current));
      setPhase('error');
      activeRef.current = false;
      setActive(false);
      // 麦克风都没开起来，这通电话不算发生过，别往聊天记录里记。
      callOutcomeRef.current = null;
    }
  }, []);

  /** 两种来电共用的开场：清空上一通的残留，把界面推到「通话中」。 */
  const openCallSession = useCallback(() => {
    if (activeRef.current) return null;
    activeRef.current = true;
    setActive(true);
    const session = sessionRef.current + 1;
    sessionRef.current = session;
    setError(null);
    setHeardText('');
    setReplyText('');
    setDeclineLine(null);
    setLevel(0);
    // Every call opens unmuted: carrying a stale mute over would look exactly
    // like a broken microphone on the next call.
    mutedRef.current = false;
    setMuted(false);
    // 上一通留在键盘面板里的草稿、以及没来得及发出去的那句话，都不该跟过来。
    keyboardOpenRef.current = false;
    setKeyboardOpen(false);
    draftRef.current = '';
    setDraftState('');
    pendingTextRef.current = null;
    // 上一通的结局不能留给这一通：挂断时它会变成聊天记录里的一条。
    callOutcomeRef.current = null;
    return session;
  }, []);

  const start = useCallback(() => {
    const session = openCallSession();
    if (session === null) return;
    // 先振铃：麦克风要等对方接了才开。
    setPhase('ringing');

    void (async () => {
      const outcome = await screenIncomingCall(session);
      if (sessionRef.current !== session) return;

      if (outcome.status === 'unreachable') {
        setPhase('unreachable');
        holdThenEnd(session, UNREACHABLE_HOLD_MS);
        return;
      }
      if (outcome.status === 'declined') {
        setDeclineLine(outcome.line);
        setPhase('declined');
        callOutcomeRef.current = { kind: 'declined', declineLine: outcome.line };
        holdThenEnd(session, DECLINED_HOLD_MS);
        return;
      }

      callOutcomeRef.current = { kind: 'connected', startedAt: Date.now() };
      await enterConnectedCall(session, outcome.reason);
    })();
  }, [enterConnectedCall, holdThenEnd, openCallSession, screenIncomingCall]);

  /**
   * 对方主动打过来，用户按了「接听」。
   *
   * 和 `start()` 的唯一区别是不振铃判断：这次电话本来就是他自己要打的，
   * 「接不接」这个决定已经由他做完了，剩下的只有用户接不接。
   */
  const answerIncoming = useCallback(() => {
    const session = openCallSession();
    if (session === null) return;
    callOutcomeRef.current = { kind: 'connected', startedAt: Date.now() };
    void enterConnectedCall(session);
  }, [enterConnectedCall, openCallSession]);

  /**
   * 挂断时把这一通的结局留进聊天记录。
   *
   * 拒接是判断层的产物，判断层不写聊天记录、也不生成回复；接通的通话虽然会以
   * 普通消息留下每句话，但看不出它们来自一通电话。两种都补一条 `system-note`，
   * 回到聊天里才看得出刚才打过电话。
   */
  const writeCallNote = useCallback(() => {
    const outcome = callOutcomeRef.current;
    callOutcomeRef.current = null;
    const conversationId = conversationRef.current?.id;
    if (!outcome || !conversationId) return;

    const message = createVoiceCallNoteMessage({
      event: outcome.kind === 'declined'
        ? { kind: 'declined', declineLine: outcome.declineLine }
        : { kind: 'connected', durationMs: Date.now() - outcome.startedAt },
      collaboratorName: personaRef.current?.name?.trim() ?? '',
      t: tRef.current
    });

    try {
      const chat = useChatStore.getState();
      const writable = chat.getConversationWritable(conversationId);
      if (writable) chat.addMessage(writable, message);
    } catch {
      // 记不上就算了：通话本身已经结束，不值得为一条记录把挂断流程炸掉。
    }
  }, []);

  const end = useCallback(() => {
    // 先记下这通电话是不是「接通过」——挂断后要不要唤醒 AI，就靠它区分。
    // 拒接 / 未接 / 判断失败时 callOutcomeRef 不是 connected，不该再唤醒。
    const wasConnected = callOutcomeRef.current?.kind === 'connected';
    const conversationId = conversationRef.current?.id ?? '';
    const collaboratorId = personaRef.current?.id ?? '';

    writeCallNote();
    // 通话结束，从桥里撤掉这通活动通话，别让 hangUp 工具再挂到一具尸体上。
    unregisterActiveVoiceCall();
    sessionRef.current += 1;
    activeRef.current = false;
    setActive(false);
    mutedRef.current = false;
    setMuted(false);
    keyboardOpenRef.current = false;
    setKeyboardOpen(false);
    draftRef.current = '';
    setDraftState('');
    pendingTextRef.current = null;
    clearDismissTimer();
    // 判断还在飞的时候就被挂断，得把它一起收掉，不然它回来时还会想改界面。
    screeningAbortRef.current?.abort();
    screeningAbortRef.current = null;
    // The native release also hands the audio mode back to the system, which is
    // what stops the whole app from being stuck on the call audio path.
    recorderRef.current?.release();
    recorderRef.current = null;
    abortRef.current?.abort();
    abortRef.current = null;
    stopPlayback();
    setLevel(0);
    setPhase('idle');
    setDeclineLine(null);
    setError(null);

    // 挂断后唤醒 AI：通话接通过、正常收线，就推它主动发一句收尾。
    if (wasConnected && conversationId && collaboratorId) {
      void notifyCallEndedRef.current({ conversationId, collaboratorId });
    }
  }, [clearDismissTimer, stopPlayback, writeCallNote]);

  // holdThenEnd 在 start 之前定义，所以它经 ref 拿到最新的 end，而不是一个旧闭包。
  useEffect(() => {
    endRef.current = end;
  }, [end]);

  const interrupt = useCallback(() => {
    abortRef.current?.abort();
    abortRef.current = null;
    stopPlayback();
  }, [stopPlayback]);

  const toggleMute = useCallback(() => {
    const next = !mutedRef.current;
    mutedRef.current = next;
    setMuted(next);
    setLevel(0);
    // Muting throws away the turn in flight: the half sentence recorded before
    // the tap should not be transcribed, sent, or answered.
    if (next) recorderRef.current?.cancel({ discard: true });
  }, []);

  const toggleSpeakerphone = useCallback(() => {
    const next = !speakerphoneRef.current;
    speakerphoneRef.current = next;
    setSpeakerphone(next);
    void recorderRef.current?.setSpeakerphone(next).catch(() => undefined);
  }, []);

  const setDraft = useCallback((value: string) => {
    draftRef.current = value;
    setDraftState(value);
  }, []);

  /**
   * 「不想说话，改成打字」。
   *
   * 打开面板的同时掐掉这一轮录音：麦克风继续开着的话，敲键盘的动静会被录进去，
   * 用户还没打完字，前半句就已经被当成一句话发出去了。
   */
  const openKeyboard = useCallback(() => {
    if (keyboardOpenRef.current) return;
    keyboardOpenRef.current = true;
    setKeyboardOpen(true);
    setLevel(0);
    recorderRef.current?.cancel({ discard: true });
  }, []);

  const closeKeyboard = useCallback(() => {
    if (!keyboardOpenRef.current) return;
    keyboardOpenRef.current = false;
    setKeyboardOpen(false);
    // 收起面板 = 放弃这句草稿，回到只用听的模式。
    draftRef.current = '';
    setDraftState('');
  }, []);

  /**
   * 发出键盘里那句话。
   *
   * 文本交给录音循环消费，而不是直接 submit —— 那样会和循环自己的
   * `submit()` 抢同一条发送链路，也会绕过 `waitForReply` 的会话失效检查。
   */
  const sendDraft = useCallback(() => {
    const text = draftRef.current.trim();
    if (!text) return;
    pendingTextRef.current = text;
    keyboardOpenRef.current = false;
    setKeyboardOpen(false);
    draftRef.current = '';
    setDraftState('');
    /*
     * 叫醒循环。它此刻可能卡在两处：等一轮录音结束（录音中），或者正在念上
     * 一句回复（朗读中）—— 打字就是在说话，说了话当然可以打断对方，所以两边
     * 一起收掉，让循环尽快回到顶部把这句话发出去。
     */
    recorderRef.current?.cancel({ discard: true });
    abortRef.current?.abort();
    abortRef.current = null;
    stopPlayback();
  }, [stopPlayback]);

  const playbackReady = Boolean(voiceGeneration.baseUrl?.trim() && voiceGeneration.apiKey?.trim());
  const transcriptionReady = Boolean(
    voiceTranscription.enabled
    && (voiceTranscription.baseUrl?.trim()
      || (voiceTranscription.reuseVoiceBaseUrl !== false && voiceGeneration.baseUrl?.trim()))
    && (voiceTranscription.apiKey?.trim()
      || (voiceTranscription.reuseVoiceBaseUrl !== false && voiceGeneration.apiKey?.trim()))
  );

  // Releasing the mic when the chat world unmounts keeps the system indicator off.
  useEffect(() => () => {
    // 换世界/离开聊天会把电话一起掐掉，那一通也得留下记录。
    writeCallNote();
    unregisterActiveVoiceCall();
    sessionRef.current += 1;
    activeRef.current = false;
    mutedRef.current = false;
    keyboardOpenRef.current = false;
    pendingTextRef.current = null;
    clearDismissTimer();
    screeningAbortRef.current?.abort();
    screeningAbortRef.current = null;
    recorderRef.current?.release();
    recorderRef.current = null;
    resolvePlaybackRef.current?.();
    resolvePlaybackRef.current = null;
    const audio = audioRef.current;
    if (audio) {
      audio.onended = null;
      audio.onerror = null;
      try {
        audio.pause();
      } catch {
        // Ignore.
      }
    }
    audioRef.current = null;
    const url = audioUrlRef.current;
    audioUrlRef.current = null;
    if (url) URL.revokeObjectURL(url);
  }, [clearDismissTimer, writeCallNote]);

  return {
    active,
    phase,
    level,
    heardText,
    replyText,
    declineLine,
    collaboratorName: persona?.name?.trim() ?? '',
    error,
    playbackReady,
    transcriptionReady,
    muted,
    speakerphone,
    speakerphoneSupported: canControlVoiceCallRoute(),
    start,
    answerIncoming,
    end,
    interrupt,
    toggleMute,
    toggleSpeakerphone,
    keyboardOpen,
    draft,
    openKeyboard,
    closeKeyboard,
    setDraft,
    sendDraft
  };
}
